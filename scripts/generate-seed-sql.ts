/**
 * Writes supabase/seed.sql from the demo source, so the local database holds
 * the same inventory as the app's demo mode. Run with `npm run seed:sql`.
 */

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { DemoSource } from '../src/data/sources/demo-source';
import { fetchAll } from '../src/domain/source';

function literal(value: string | number | null): string {
  if (value === null) return 'null';
  if (typeof value === 'number') return String(value);
  return `'${value.replaceAll("'", "''")}'`;
}

async function main() {
  const vehicles = await fetchAll(new DemoSource());
  const rows = vehicles.map((v) =>
    [
      v.source,
      v.sourceId,
      v.make,
      v.model,
      v.variant,
      v.year,
      v.mileageKm,
      v.powerKw,
      v.fuel,
      v.transmission,
      v.bodyType,
      v.priceEur,
      v.zip,
      v.city,
      JSON.stringify(v.images),
      v.sourceUrl,
    ]
      .map(literal)
      .join(', '),
  );

  const sql = `-- Generated by scripts/generate-seed-sql.ts. Do not edit by hand.
insert into public.vehicles
  (source, source_id, make, model, variant, year, mileage_km, power_kw, fuel, transmission, body_type, price_eur, zip, city, images, source_url)
values
${rows.map((row) => `  (${row})`).join(',\n')}
on conflict (source, source_id) do nothing;
`;

  const target = join(__dirname, '..', 'supabase', 'seed.sql');
  writeFileSync(target, sql);
  console.log(`Wrote ${vehicles.length} vehicles to ${target}`);
}

main();
